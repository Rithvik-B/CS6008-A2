#!/bin/sh
# sign-all.sh -- build the DNSSEC chain of trust for the lab.
# Signs the three zones child-first so each child's DS can be published in its
# parent, then derives the resolver's trust anchor from the root KSK.
# Algorithm 13 = ECDSAP256SHA256 (small keys, fast; see report).
# Run from the phase3/ directory, inside the lab image:
#   docker run --rm -v "$PWD":/phase3 -w /phase3 cs6008-dnslab:base sign/sign-all.sh
set -e
ALG=ECDSAP256SHA256
cd "$(dirname "$0")/.."                       # -> phase3/
ROOT=config/root-ns; TLD=config/tld-ns; DOM=config/domain-ns; RES=config/resolver

echo "[sign] cleaning previous keys/signed zones"
rm -rf keys build
mkdir -p keys/root keys/com keys/example.com build
rm -f "$ROOT/db.root.signed" "$TLD/db.com.signed" "$DOM/db.example.com.signed" "$RES/trust-anchor.conf"

sign_zone() {                                 # <zone> <keydir> <zonefile-to-sign> <signed-out>
    zone="$1"; kd="$2"; src="$3"; out="$4"
    echo "[sign] generating ZSK+KSK for $zone ($ALG)"
    dnssec-keygen -a "$ALG" -n ZONE        -K "$kd" "$zone" >/dev/null
    dnssec-keygen -a "$ALG" -n ZONE -f KSK -K "$kd" "$zone" >/dev/null
    echo "[sign] signing $zone"
    dnssec-signzone -S -K "$kd" -o "$zone" -f "$out" -d keys "$src" >/dev/null
    echo "[sign]   -> $out"
}

# ---- 1. example.com (leaf): sign, emit DS into keys/dsset-example.com. ----
cp "$DOM/db.example.com" build/db.example.com
sign_zone example.com keys/example.com build/db.example.com "$DOM/db.example.com.signed"

# ---- 2. com: publish example.com's DS, then sign; emit DS for com ----
cat "$TLD/db.com" keys/dsset-example.com. > build/db.com
sign_zone com keys/com build/db.com "$TLD/db.com.signed"

# ---- 3. root (.): publish com's DS, then sign ----
cat "$ROOT/db.root" keys/dsset-com. > build/db.root
sign_zone . keys/root build/db.root "$ROOT/db.root.signed"

# ---- 4. resolver trust anchor = root KSK (flags 257) ----
echo "[sign] writing resolver trust anchor from the root KSK"
ksk=$(grep -l "IN DNSKEY 257" keys/root/K*.key | head -1)
key=$(grep "IN DNSKEY 257" "$ksk" | sed 's/.*DNSKEY //' )
set -- $key                                   # $1=flags $2=proto $3=alg, rest=base64
flags=$1; proto=$2; alg=$3; shift 3; b64="$*"
{
  echo "// Root KSK trust anchor (generated by sign/sign-all.sh). The ONLY anchor."
  echo "trust-anchors {"
  echo "    . static-key $flags $proto $alg \"$b64\";"
  echo "};"
} > "$RES/trust-anchor.conf"

echo "[sign] DONE. DS chain:"
echo "  com.         DS (in root) :"; grep DS keys/dsset-com.        | sed 's/^/    /'
echo "  example.com. DS (in com)  :"; grep DS keys/dsset-example.com. | sed 's/^/    /'
echo "  trust anchor ($RES/trust-anchor.conf):"; sed 's/^/    /' "$RES/trust-anchor.conf"
